"""Logging configuration for test runs"""
import logging
from pathlib import Path


def configure_logger():
    """Configures file logging (DEBUG level) in the project root and suppresses Selenium noise"""
    log_path = Path(__file__).resolve().parent.parent / "test.log"

    file_handler = logging.FileHandler(log_path, mode="w", encoding="utf-8")
    file_handler.setLevel(logging.DEBUG)
    file_handler.setFormatter(
        logging.Formatter("%(asctime)s - %(name)s - %(levelname)s - %(message)s")
    )

    root_logger = logging.getLogger()
    root_logger.setLevel(logging.DEBUG)
    root_logger.addHandler(file_handler)

    # Removing technical spam generated by Selenium itself
    logging.getLogger("selenium").setLevel(logging.WARNING)
    logging.getLogger("urllib3").setLevel(logging.WARNING)
